import type { Block } from '@/lib/db/blocks';
import { useBlocksStore } from '@/stores/blocksStore';
import { useThreadsStore } from '@/stores/threadsStore';
import { DIGITS, DIGIT_ADVANCE, UNITS_PER_EM } from './seqDigits';

// The block's own number, drawn as a ring.
//
// Ocean 2026-08-10: 「# 看起来太凌乱」 — `#1 8/7 16:50` put two runs of monospace digits side by side and the eye
// could not tell where the number ended and the clock began; the ring separates them with a shape. Not ①②③:
// those code points stop at 50. The number itself is unchanged — an AI over MCP still says 「#12」 and the pack
// still writes `#12`; the ring is a skin over the same integer (the header's tooltip spells the mapping out).
//
// 2026-11-10 (Ocean, Mac and Windows: 「数字+圆圈没有对齐，看起来不专业……可以永远保证数字在圆心位置，且不会超出圆」,
// chose 甲 「正圆，一个项目里一样大」):
// - The digits are DRAWN, from Geist Mono's own outlines (seqDigits.ts, generated by scripts/gen-seq-digits.py),
//   not typeset. The CSS ring before this centred text with flex plus a padding measured in WebKit (cf6395a);
//   where a browser puts a glyph in its line box is an engine-and-density property, so WebView2 at 250% put the
//   digit low, and two digits stretched the ring into an oval. Outlines have a known ink box: its centre is put
//   on the ring's centre by arithmetic, and `ringFor` sizes the digits so the box's corners stay inside the ring
//   for every number with that many digits (SeqBadge.test.ts walks all of them up to 99 999).
// - One size per project: the ring's digit count is that of the open project's highest number, so every ring
//   in the timeline (and the rail, the gist board…) is the same circle with the same digits, and the clocks
//   after them line up. A number with more digits than that (a citation into a bigger project) gets the ring
//   its own digits need — a ring the digits do not fit is the one thing this must never draw.

const STROKE = 1;
/** Clear space between the digits' ink and the inside of the stroke. */
const GAP = 0.75;
/** The digit size the ring was drawn with when it held one digit — the size of the clock text beside it. */
const MAX_FONT = 9;

const inkLeft = Math.min(...DIGITS.map((g) => g.x0));
const inkRight = Math.max(...DIGITS.map((g) => g.x1));
const inkBottom = Math.min(...DIGITS.map((g) => g.y0));
const inkTop = Math.max(...DIGITS.map((g) => g.y1));

/** Ring diameter and digit size (px) for a ring that holds `digits` digits. 13 / 15 / 18 / 22, then +4. */
export const ringFor = (digits: number): { diameter: number; font: number } => {
  const n = Math.max(1, Math.floor(digits));
  const diameter = n === 1 ? 13 : n === 2 ? 15 : n === 3 ? 18 : 22 + 4 * (n - 4);
  const room = diameter / 2 - STROKE - GAP;
  // The widest and tallest n digits can be, in em: corner of that box must sit within `room` of the centre.
  const halfW = ((n - 1) * DIGIT_ADVANCE + inkRight - inkLeft) / 2 / UNITS_PER_EM;
  const halfH = (inkTop - inkBottom) / 2 / UNITS_PER_EM;
  return { diameter, font: Math.min(MAX_FONT, room / Math.hypot(halfW, halfH)) };
};

/** Where `text`'s digits go in a ring: the transform that puts their ink box's centre on the ring's centre. */
export const digitLayout = (text: string, ring: { diameter: number; font: number }) => {
  const glyphs = [...text].map((c) => DIGITS[Number(c)]);
  const last = glyphs.length - 1;
  const x0 = glyphs[0].x0;
  const x1 = last * DIGIT_ADVANCE + glyphs[last].x1;
  const y0 = Math.min(...glyphs.map((g) => g.y0));
  const y1 = Math.max(...glyphs.map((g) => g.y1));
  const scale = ring.font / UNITS_PER_EM;
  const c = ring.diameter / 2;
  // Font units are y-up; the SVG is y-down, hence the flip.
  return { glyphs, scale, tx: c - (scale * (x0 + x1)) / 2, ty: c + (scale * (y0 + y1)) / 2, box: { x0, x1, y0, y1 } };
};

const digitCount = (n: number): number => String(Math.max(0, Math.floor(n))).length;

// The project's highest number, worked out once per block list (the list is replaced, not mutated, on change).
const highest = new WeakMap<Block[], number>();
export const projectDigits = (blocks: Block[] | undefined): number => {
  if (!blocks) return 1;
  let max = highest.get(blocks);
  if (max === undefined) {
    max = 0;
    for (const b of blocks) if (b.seq != null && b.seq > max) max = b.seq;
    highest.set(blocks, max);
  }
  return digitCount(max);
};

export default function SeqBadge({ seq, className = '' }: { seq: number; className?: string }) {
  const activeId = useThreadsStore((s) => s.activeId);
  const inProject = useBlocksStore((s) => projectDigits(activeId ? s.byThread[activeId] : undefined));
  const text = String(Math.max(0, Math.floor(seq)));
  const ring = ringFor(Math.max(inProject, text.length));
  const { glyphs, scale, tx, ty } = digitLayout(text, ring);
  const d = ring.diameter;
  return (
    <svg
      width={d}
      height={d}
      viewBox={`0 0 ${d} ${d}`}
      role="img"
      aria-label={`#${text}`}
      // A drawn badge has no text baseline: centre it on the row (flex rows) / on the line (inline).
      className={`inline-block shrink-0 self-center align-middle ${className}`}
    >
      <circle cx={d / 2} cy={d / 2} r={d / 2 - STROKE / 2} fill="none" stroke="currentColor" strokeWidth={STROKE} />
      <g fill="currentColor" transform={`translate(${tx} ${ty}) scale(${scale} ${-scale})`}>
        {glyphs.map((g, i) => (
          <path key={i} d={g.d} transform={i ? `translate(${i * DIGIT_ADVANCE} 0)` : undefined} />
        ))}
      </g>
    </svg>
  );
}
