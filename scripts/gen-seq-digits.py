"""Writes src/components/ThreadView/seqDigits.ts: the outlines of the digits 0-9 from the bundled Geist Mono
(weight 400, the weight the block clock beside the badge uses), for SeqBadge to draw as shapes.

Why shapes and not text (Ocean 2026-11-10: the number is not in the middle of its ring, on the Mac or on
Windows): where a browser puts a digit inside a box depends on the engine's baseline placement and on the
screen's pixel density. WebKit and WebView2 disagree, and a padding that cancels one moves the other.
Drawn from the font's own outlines, the digits' ink box is known exactly, so the badge can put its
centre on the ring's centre with arithmetic and prove that it never reaches the ring.

Usage: python3 scripts/gen-seq-digits.py   (needs fontTools). Geist Mono is under the SIL OFL 1.1
(src/assets/fonts/OFL-GeistMono.txt), which allows embedding it in the app.
"""
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / 'src/assets/fonts/GeistMono[wght].ttf'
OUT = ROOT / 'src/components/ThreadView/seqDigits.ts'

font = TTFont(FONT)
upm = font['head'].unitsPerEm
glyphs = font.getGlyphSet(location={'wght': 400})
cmap = font.getBestCmap()

rows = []
advance = None
for ch in '0123456789':
    g = glyphs[cmap[ord(ch)]]
    advance = advance or g.width
    assert g.width == advance, 'Geist Mono digits are expected to share one advance'
    path, bounds = SVGPathPen(glyphs), BoundsPen(glyphs)
    g.draw(path)
    g.draw(bounds)
    x0, y0, x1, y1 = bounds.bounds
    rows.append(f"  {{ d: '{path.getCommands()}', x0: {x0:g}, y0: {y0:g}, x1: {x1:g}, y1: {y1:g} }}, // {ch}")

OUT.write_text(
    '// Generated by scripts/gen-seq-digits.py from src/assets/fonts/GeistMono[wght].ttf (wght 400).\n'
    '// Geist Mono: SIL Open Font License 1.1 (src/assets/fonts/OFL-GeistMono.txt). Do not edit by hand.\n'
    '//\n'
    '// The digits 0-9 as outlines in font units (y up, baseline at 0), with each one\'s ink box.\n'
    '\n'
    f'/** Font units per em. */\nexport const UNITS_PER_EM = {upm};\n'
    f'/** Every digit\'s advance (the font is monospaced). */\nexport const DIGIT_ADVANCE = {advance:g};\n'
    '\n'
    'export type DigitOutline = { d: string; x0: number; y0: number; x1: number; y1: number };\n'
    '\n'
    '/** Indexed by the digit\'s value. */\n'
    'export const DIGITS: readonly DigitOutline[] = [\n' + '\n'.join(rows) + '\n];\n'
)
print(f'wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size} bytes)')
